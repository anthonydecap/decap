const COPY: Record<UrlLocale, UiCopy> = { en, fr, nl, de };

export function uiCopy(lang: string): UiCopy {
  return COPY[resolveUrlLang(lang)];
}

/** Interface texts for the language in the current URL. */
export function useUiCopy(): UiCopy {
  const pathname = usePathname() ?? "/en";
  return uiCopy(pathname.split("/").filter(Boolean)[0] ?? "en");
}
