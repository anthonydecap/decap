export type SupportAbout = About;
export const SUPPORT_ABOUTS: About[] = ["player", "music", "software", "order", "account", "other"];

/** Which ticket categories each "What is this about?" answer offers (first is the default). */
export const ABOUT_CATEGORIES: Record<About, string[]> = {
  player: ["PLAYER_PROBLEM", "PLAYER_REGISTRATION"],
  music: ["MUSIC_DOWNLOAD", "MUSIC_PLAYBACK", "ARRANGEMENT_QUESTION"],
  software: ["SOFTWARE_PROBLEM", "SOFTWARE_ACTIVATION"],
  order: ["ORDER_PAYMENT", "BILLING", "REFUND_REQUEST"],
  account: ["ACCOUNT"],
  other: ["OTHER"],
};

export function aboutForCategory(category: string | undefined): About | undefined {
  if (!category) return undefined;
  return SUPPORT_ABOUTS.find((a) => ABOUT_CATEGORIES[a].includes(category));
}
