/** Builds a tiny valid format-1 MIDI file for tests (no copyrighted content). */
export function buildMidi(opts: { bpm?: number; ppq?: number; withSysEx?: boolean } = {}): Uint8Array {
  const ppq = opts.ppq ?? 480;
  const usPerQuarter = Math.round(60_000_000 / (opts.bpm ?? 100));
  const header = [0x4d, 0x54, 0x68, 0x64, 0, 0, 0, 6, 0, 1, 0, 2, (ppq >> 8) & 0xff, ppq & 0xff];

  const conductor = [
    0x00, 0xff, 0x03, 0x04, ...ascii("Song"),
    0x00, 0xff, 0x51, 0x03, (usPerQuarter >> 16) & 0xff, (usPerQuarter >> 8) & 0xff, usPerQuarter & 0xff,
    0x00, 0xff, 0x58, 0x04, 0x03, 0x02, 0x18, 0x08, // 3/4
    0x00, 0xff, 0x59, 0x02, 0xff, 0x01, // 1 flat, minor → D minor
    0x00, 0xff, 0x06, 0x05, ...ascii("Intro"),
    0x00, 0xff, 0x2f, 0x00,
  ];
  const notes = [
    0x00, 0xc0, 0x00, // program change ch1 → piano
    ...(opts.withSysEx ? [0x00, 0xf0, 0x03, 0x7e, 0x7f, 0xf7] : []),
    0x00, 0x90, 0x3c, 0x64, // note on C4
    0x83, 0x60, 0x3c, 0x00, // delta 480, running status note-off via vel 0
    0x00, 0x91, 0x40, 0x64, // ch2
    0x83, 0x60, 0x80 | 0x01, 0x40, 0x00, // note off ch2
    0x00, 0xff, 0x2f, 0x00,
  ];
  return new Uint8Array([...header, ...chunk(conductor), ...chunk(notes)]);
}

function ascii(s: string) {
  return [...s].map((c) => c.charCodeAt(0));
}

function chunk(body: number[]) {
  const n = body.length;
  return [0x4d, 0x54, 0x72, 0x6b, (n >>> 24) & 0xff, (n >> 16) & 0xff, (n >> 8) & 0xff, n & 0xff, ...body];
}
